package router

import "net/http"

type Endpoints interface {
	Notifications(http.ResponseWriter, *http.Request)
	UpdateNotificationPreferences(http.ResponseWriter, *http.Request)
	SubscribePush(http.ResponseWriter, *http.Request)
	RevokePush(http.ResponseWriter, *http.Request)
	RunJobs(http.ResponseWriter, *http.Request)
	IngestError(http.ResponseWriter, *http.Request)
	Register(http.ResponseWriter, *http.Request)
	Login(http.ResponseWriter, *http.Request)
	Me(http.ResponseWriter, *http.Request)
	Logout(http.ResponseWriter, *http.Request)
	Password(http.ResponseWriter, *http.Request)
	FocusState(http.ResponseWriter, *http.Request)
	StartFocus(http.ResponseWriter, *http.Request)
	ChangeFocus(http.ResponseWriter, *http.Request)
	GetSeries(http.ResponseWriter, *http.Request)
	CreateSeries(http.ResponseWriter, *http.Request)
	StopSeries(http.ResponseWriter, *http.Request)
	RestoreSeries(http.ResponseWriter, *http.Request)
	Calendar(http.ResponseWriter, *http.Request)
	PeriodReport(http.ResponseWriter, *http.Request)
	DayDetails(http.ResponseWriter, *http.Request)
	ScheduleTask(http.ResponseWriter, *http.Request)
	UndoSchedule(http.ResponseWriter, *http.Request)
	ListTasks(http.ResponseWriter, *http.Request)
	CreateTask(http.ResponseWriter, *http.Request)
	GetTask(http.ResponseWriter, *http.Request)
	EditTask(http.ResponseWriter, *http.Request)
	DeleteTask(http.ResponseWriter, *http.Request)
	CompleteTask(http.ResponseWriter, *http.Request)
	RestoreTask(http.ResponseWriter, *http.Request)
	TaskFocus(http.ResponseWriter, *http.Request)
	ListGroups(http.ResponseWriter, *http.Request)
	CreateGroup(http.ResponseWriter, *http.Request)
	EditGroup(http.ResponseWriter, *http.Request)
	DeleteGroup(http.ResponseWriter, *http.Request)
	GetSettings(http.ResponseWriter, *http.Request)
	EditSettings(http.ResponseWriter, *http.Request)
	Health(http.ResponseWriter, *http.Request)
	Ready(http.ResponseWriter, *http.Request)
}

func New(s Endpoints) http.Handler {
	mux := http.NewServeMux()
	mux.HandleFunc("GET /api/v1/notifications", s.Notifications)
	mux.HandleFunc("PUT /api/v1/notifications/preferences", s.UpdateNotificationPreferences)
	mux.HandleFunc("POST /api/v1/notifications/subscriptions", s.SubscribePush)
	mux.HandleFunc("DELETE /api/v1/notifications/subscriptions/{id}", s.RevokePush)
	mux.HandleFunc("POST /internal/jobs", s.RunJobs)
	mux.HandleFunc("POST /api/v1/monitoring/errors", s.IngestError)
	mux.HandleFunc("POST /api/v1/auth/register", s.Register)
	mux.HandleFunc("POST /api/v1/auth/login", s.Login)
	mux.HandleFunc("GET /api/v1/auth/me", s.Me)
	mux.HandleFunc("POST /api/v1/auth/logout", s.Logout)
	mux.HandleFunc("POST /api/v1/auth/password", s.Password)
	mux.HandleFunc("GET /api/v1/focus", s.FocusState)
	mux.HandleFunc("POST /api/v1/focus", s.StartFocus)
	mux.HandleFunc("POST /api/v1/focus/{id}/{action}", s.ChangeFocus)
	mux.HandleFunc("GET /api/v1/series/{id}", s.GetSeries)
	mux.HandleFunc("POST /api/v1/series", s.CreateSeries)
	mux.HandleFunc("POST /api/v1/series/{id}/stop", s.StopSeries)
	mux.HandleFunc("POST /api/v1/series/{id}/restore", s.RestoreSeries)
	mux.HandleFunc("GET /api/v1/calendar", s.Calendar)
	mux.HandleFunc("GET /api/v1/reports/period", s.PeriodReport)
	mux.HandleFunc("GET /api/v1/reports/days/{date}", s.DayDetails)
	mux.HandleFunc("POST /api/v1/tasks/{id}/schedule", s.ScheduleTask)
	mux.HandleFunc("POST /api/v1/undo/{id}", s.UndoSchedule)
	mux.HandleFunc("GET /api/v1/tasks", s.ListTasks)
	mux.HandleFunc("POST /api/v1/tasks", s.CreateTask)
	mux.HandleFunc("GET /api/v1/tasks/{id}", s.GetTask)
	mux.HandleFunc("PATCH /api/v1/tasks/{id}", s.EditTask)
	mux.HandleFunc("DELETE /api/v1/tasks/{id}", s.DeleteTask)
	mux.HandleFunc("POST /api/v1/tasks/{id}/completion", s.CompleteTask)
	mux.HandleFunc("POST /api/v1/tasks/{id}/restore", s.RestoreTask)
	mux.HandleFunc("GET /api/v1/tasks/{id}/focus", s.TaskFocus)
	mux.HandleFunc("GET /api/v1/groups", s.ListGroups)
	mux.HandleFunc("POST /api/v1/groups", s.CreateGroup)
	mux.HandleFunc("PATCH /api/v1/groups/{id}", s.EditGroup)
	mux.HandleFunc("DELETE /api/v1/groups/{id}", s.DeleteGroup)
	mux.HandleFunc("GET /api/v1/settings", s.GetSettings)
	mux.HandleFunc("PATCH /api/v1/settings", s.EditSettings)
	mux.HandleFunc("GET /healthz", s.Health)
	mux.HandleFunc("GET /readyz", s.Ready)
	return mux
}
