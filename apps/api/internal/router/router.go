package router

import (
	"focuscalendar/internal/diagnostics"
	"net/http"
)

type Endpoints interface {
	FollowingDeletionPreview(http.ResponseWriter, *http.Request)
	Notifications(http.ResponseWriter, *http.Request)
	UpdateNotificationPreferences(http.ResponseWriter, *http.Request)
	SubscribePush(http.ResponseWriter, *http.Request)
	RevokePush(http.ResponseWriter, *http.Request)
	RunJobs(http.ResponseWriter, *http.Request)
	IngestError(http.ResponseWriter, *http.Request)
	Register(http.ResponseWriter, *http.Request)
	Login(http.ResponseWriter, *http.Request)
	Refresh(http.ResponseWriter, *http.Request)
	Me(http.ResponseWriter, *http.Request)
	Logout(http.ResponseWriter, *http.Request)
	Password(http.ResponseWriter, *http.Request)
	FocusState(http.ResponseWriter, *http.Request)
	StartFocus(http.ResponseWriter, *http.Request)
	ChangeFocus(http.ResponseWriter, *http.Request)
	GetSeries(http.ResponseWriter, *http.Request)
	CreateSeries(http.ResponseWriter, *http.Request)
	StopSeries(http.ResponseWriter, *http.Request)
	RestoreSeries(http.ResponseWriter, *http.Request)
	Calendar(http.ResponseWriter, *http.Request)
	PeriodReport(http.ResponseWriter, *http.Request)
	DayDetails(http.ResponseWriter, *http.Request)
	ScheduleTask(http.ResponseWriter, *http.Request)
	UndoSchedule(http.ResponseWriter, *http.Request)
	ListTasks(http.ResponseWriter, *http.Request)
	CreateTask(http.ResponseWriter, *http.Request)
	GetTask(http.ResponseWriter, *http.Request)
	EditTask(http.ResponseWriter, *http.Request)
	DeleteTask(http.ResponseWriter, *http.Request)
	CompleteTask(http.ResponseWriter, *http.Request)
	RestoreTask(http.ResponseWriter, *http.Request)
	TaskFocus(http.ResponseWriter, *http.Request)
	ListGroups(http.ResponseWriter, *http.Request)
	CreateGroup(http.ResponseWriter, *http.Request)
	EditGroup(http.ResponseWriter, *http.Request)
	DeleteGroup(http.ResponseWriter, *http.Request)
	GetSettings(http.ResponseWriter, *http.Request)
	EditSettings(http.ResponseWriter, *http.Request)
	EditWorkspaceSettings(http.ResponseWriter, *http.Request)
	Health(http.ResponseWriter, *http.Request)
	Ready(http.ResponseWriter, *http.Request)
}

func New(s Endpoints) http.Handler {
	mux := http.NewServeMux()
	handle := func(pattern string, handler http.HandlerFunc) {
		mux.HandleFunc(pattern, func(w http.ResponseWriter, r *http.Request) {
			diagnostics.SetRoute(r.Context(), pattern)
			handler(w, r)
		})
	}
	handle("PATCH /api/v1/settings/workspace", s.EditWorkspaceSettings)
	handle("GET /api/v1/tasks/{id}/following-deletion-preview", s.FollowingDeletionPreview)
	handle("GET /api/v1/notifications", s.Notifications)
	handle("PUT /api/v1/notifications/preferences", s.UpdateNotificationPreferences)
	handle("POST /api/v1/notifications/subscriptions", s.SubscribePush)
	handle("DELETE /api/v1/notifications/subscriptions/{id}", s.RevokePush)
	handle("POST /internal/jobs", s.RunJobs)
	handle("POST /api/v1/monitoring/errors", s.IngestError)
	handle("POST /api/v1/auth/register", s.Register)
	handle("POST /api/v1/auth/login", s.Login)
	handle("GET /api/v1/auth/me", s.Me)
	handle("POST /api/v1/auth/refresh", s.Refresh)
	handle("POST /api/v1/auth/logout", s.Logout)
	handle("POST /api/v1/auth/password", s.Password)
	handle("GET /api/v1/focus", s.FocusState)
	handle("POST /api/v1/focus", s.StartFocus)
	handle("POST /api/v1/focus/{id}/{action}", s.ChangeFocus)
	handle("GET /api/v1/series/{id}", s.GetSeries)
	handle("POST /api/v1/series", s.CreateSeries)
	handle("POST /api/v1/series/{id}/stop", s.StopSeries)
	handle("POST /api/v1/series/{id}/restore", s.RestoreSeries)
	handle("GET /api/v1/calendar", s.Calendar)
	handle("GET /api/v1/reports/period", s.PeriodReport)
	handle("GET /api/v1/reports/days/{date}", s.DayDetails)
	handle("POST /api/v1/tasks/{id}/schedule", s.ScheduleTask)
	handle("POST /api/v1/undo/{id}", s.UndoSchedule)
	handle("GET /api/v1/tasks", s.ListTasks)
	handle("POST /api/v1/tasks", s.CreateTask)
	handle("GET /api/v1/tasks/{id}", s.GetTask)
	handle("PATCH /api/v1/tasks/{id}", s.EditTask)
	handle("DELETE /api/v1/tasks/{id}", s.DeleteTask)
	handle("POST /api/v1/tasks/{id}/completion", s.CompleteTask)
	handle("POST /api/v1/tasks/{id}/restore", s.RestoreTask)
	handle("GET /api/v1/tasks/{id}/focus", s.TaskFocus)
	handle("GET /api/v1/groups", s.ListGroups)
	handle("POST /api/v1/groups", s.CreateGroup)
	handle("PATCH /api/v1/groups/{id}", s.EditGroup)
	handle("DELETE /api/v1/groups/{id}", s.DeleteGroup)
	handle("GET /api/v1/settings", s.GetSettings)
	handle("PATCH /api/v1/settings", s.EditSettings)
	handle("GET /healthz", s.Health)
	handle("GET /readyz", s.Ready)
	return mux
}
